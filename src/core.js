/**
 * Validate that `byte` is a value in the range 0..255 inclusive.
 *
 * A separate guard exists (rather than relying on the array returning
 * `undefined` for out-of-range indices) so that callers get a clear
 * `RangeError` instead of a downstream `TypeError` when they try to use the
 * result as a number.
 */
function assertByte(byte) {
  if (!Number.isInteger(byte)) {
    throw new TypeError(`EFM input must be an integer, got ${typeof byte}`);
  }
  if (byte < 0 || byte > 255) {
    throw new RangeError(`EFM input must be in 0..255, got ${byte}`);
  }
}

/**
 * Encode a single byte (0..255) into its 14-bit EFM channel word.
 *
 * Returns the channel word as a number, e.g. 0x2400 for byte 0. The number is
 * always in the range 0..16383 because the EFM table only contains 14-bit
 * values.
 */
export function encodeByte(byte) {
  assertByte(byte);
  return EFM_TABLE[byte];
}

/**
 * Format a single 14-bit EFM channel word as a zero-padded 14-character binary
 * string.
 *
 * Used for display and for tests that need to inspect run lengths visually.
 * `toString(2)` on a number with leading zeros would drop them, which is
 * exactly what we do NOT want for a channel word, hence the explicit padding.
 */
export function formatChannelWord(word) {
  if (!Number.isInteger(word) || word < 0 || word > 0x3fff) {
    throw new RangeError(`Not a 14-bit word: ${word}`);
  }
  return word.toString(2).padStart(14, '0');
}

/**
 * Encode an iterable of bytes into a Uint16Array of 14-bit channel words.
 *
 * The result is a Uint16Array (not a regular Array) because the caller of an
 * encoder usually wants a compact, typed buffer to feed into a frame builder.
 * Each element is in the range 0..16383 and fits in 16 bits.
 */
export function encodeBytes(bytes) {
  const out = [];
  for (const b of bytes) {
    out.push(encodeByte(b));
  }
  return Uint16Array.from(out);
}

/**
 * The minimum and maximum run length of zeros guaranteed between any two
 * '1' bits inside a single EFM channel word. Exposed so that callers and tests
 * can reason about the run-length property without hard-coding magic numbers.
 */
export const EFM_RUN_LENGTH = Object.freeze({ min: 2, max: 10 });
